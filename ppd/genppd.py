#!/usr/bin/env python3
"""Generate the rastertotspl PPD.

Usage: genppd.py FILTER_PATH > rastertotspl.ppd

Option keywords (including the misspelled "AdjustHoriaontal") deliberately match
the vendor JIOSE PPD, so queues created with either PPD work with rastertotspl.
"""
import sys

if len(sys.argv) != 2:
    sys.exit(__doc__)
FILTER = sys.argv[1]

MM = 72 / 25.4

# (name, label, width pt, height pt)
SIZES = [
    ("w288h432", '4.00x6.00"', 288, 432),  # standard shipping label
    ("w288h144", '4.00x2.00"', 288, 144),
    ("w288h216", '4.00x3.00"', 288, 216),
    ("w288h288", '4.00x4.00"', 288, 288),
    ("w288h360", '4.00x5.00"', 288, 360),
    ("w288h468", '4.00x6.50"', 288, 468),
    ("w288h576", '4.00x8.00"', 288, 576),
    ("w216h72", '3.00x1.00"', 216, 72),
    ("w216h144", '3.00x2.00"', 216, 144),
    ("w216h216", '3.00x3.00"', 216, 216),
    ("w162h90", '2.25x1.25"', 162, 90),
    ("w144h72", '2.00x1.00"', 144, 72),
    ("w144h144", '2.00x2.00"', 144, 144),
    ("w108h72", '1.50x1.00"', 108, 72),
    ("w72h72", '1.00x1.00"', 72, 72),
]
for w_mm, h_mm in [(100, 100), (100, 150), (100, 200), (80, 50), (60, 40), (50, 30), (40, 30)]:
    w, h = round(w_mm * MM), round(h_mm * MM)
    SIZES.append((f"w{w}h{h}", f"{w_mm}x{h_mm}mm", w, h))

out = []
p = out.append

p(f"""*PPD-Adobe: "4.3"
*% Generated by ppd/genppd.py (rastertotspl). Do not edit by hand.
*FormatVersion: "4.3"
*FileVersion: "1.0.0"
*LanguageVersion: English
*LanguageEncoding: ISOLatin1
*PCFileName: "RTOTSPL.PPD"
*Manufacturer: "JIOSE"
*Product: "(J500)"
*ModelName: "JIOSE J500"
*ShortNickName: "JIOSE J500 (rastertotspl)"
*NickName: "JIOSE J500 TSPL (rastertotspl, native)"
*1284DeviceID: "MFG:JIOSE;MDL:J500;"
*PSVersion: "(3010.000) 0"
*LanguageLevel: "3"
*ColorDevice: False
*DefaultColorSpace: Gray
*FileSystem: False
*Throughput: "1"
*LandscapeOrientation: Plus90
*TTRasterizer: Type42
*cupsVersion: 1.2
*cupsModelNumber: 20
*cupsManualCopies: True
*cupsFilter: "application/vnd.cups-raster 0 {FILTER}"

*OpenUI *PageSize/Media Size: PickOne
*OrderDependency: 10 AnySetup *PageSize
*DefaultPageSize: w288h432""")
for n, l, w, h in SIZES:
    p(f'*PageSize {n}/{l}: "<</PageSize[{w} {h}]/ImagingBBox null>>setpagedevice"')
p("*CloseUI: *PageSize\n")

p("""*OpenUI *PageRegion/Media Size: PickOne
*OrderDependency: 10 AnySetup *PageRegion
*DefaultPageRegion: w288h432""")
for n, l, w, h in SIZES:
    p(f'*PageRegion {n}/{l}: "<</PageSize[{w} {h}]/ImagingBBox null>>setpagedevice"')
p("*CloseUI: *PageRegion\n")

p("*DefaultImageableArea: w288h432")
for n, l, w, h in SIZES:
    p(f'*ImageableArea {n}/{l}: "0 0 {w} {h}"')
p("\n*DefaultPaperDimension: w288h432")
for n, l, w, h in SIZES:
    p(f'*PaperDimension {n}/{l}: "{w} {h}"')

p("""
*MaxMediaWidth: "294"
*MaxMediaHeight: "5670"
*HWMargins: 0 0 0 0
*CustomPageSize True: "pop pop pop <</PageSize[5 -2 roll]/ImagingBBox null>>setpagedevice"
*ParamCustomPageSize Width: 1 points 36 294
*ParamCustomPageSize Height: 2 points 36 5670
*ParamCustomPageSize WidthOffset: 3 points 0 0
*ParamCustomPageSize HeightOffset: 4 points 0 0
*ParamCustomPageSize Orientation: 5 int 0 0

*OpenUI *Resolution/Resolution: PickOne
*OrderDependency: 10 AnySetup *Resolution
*DefaultResolution: 203dpi
*Resolution 203dpi/203 dpi: "<</HWResolution[203 203]/cupsBitsPerColor 8/cupsColorSpace 0>>setpagedevice"
*CloseUI: *Resolution

*OpenGroup: PageSet/Print Options
""")


def pick(key, label, order, default, choices):
    p(f"*OpenUI *{key}/{label}: PickOne")
    p(f"*OrderDependency: {order} AnySetup *{key}")
    p(f"*Default{key}: {default}")
    for c, t in choices:
        p(f'*{key} {c}/{t}: ""')
    p(f"*CloseUI: *{key}\n")


def mm_range(lo, hi):
    return [(str(i), f"{i}mm") for i in range(lo, hi + 1)]


pick("Darkness", "Darkness", 20, "8", [("Default", "Printer Default")] + [(str(i), str(i)) for i in range(16)])
pick("zePrintRate", "Speed", 20, "4", [("Default", "Printer Default")] + [(str(i), f"{i} inch/sec.") for i in range(1, 9)])
pick("zeMediaTracking", "Media Type", 20, "Gap", [("Continuous", "Continuous"), ("Gap", "Gap"), ("BLine", "Black Mark")])
pick("GapOrMarkHeight", "Gap/Mark Height", 160, "3", mm_range(0, 10))
pick("GapOrMarkOffset", "Gap/Mark Offset", 160, "0", mm_range(0, 10))
pick("Rotate", "Print Direction", 160, "0", [("0", "Normal"), ("1", "Reversed")])
pick("AdjustHoriaontal", "Horizontal Adjust", 130, "0", mm_range(-20, 20))
pick("AdjustVertical", "Vertical Adjust", 130, "0", mm_range(-20, 20))
pick("FeedOffset", "Feed after Print", 160, "0", mm_range(-20, 20))
pick("AutoDotted", "Dotted Line Between Labels", 160, "0", [("0", "Off"), ("1", "On")])

p("*CloseGroup: PageSet")
print("\n".join(out))
